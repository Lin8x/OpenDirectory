//! Physical keys, by the browser's `KeyboardEvent.code`, mapped to Linux
//! evdev key codes and Windows set-1 scan codes (with the E0 "extended"
//! prefix flag). Positions, not characters, so any keyboard layout works.

#[allow(dead_code)] // each OS reads its own fields
pub struct Key {
    pub evdev: u16,
    pub scan: u16,
    pub ext: bool,
}

const fn k(evdev: u16, scan: u16, ext: bool) -> Key {
    Key { evdev, scan, ext }
}

/// For the main block, evdev codes equal set-1 scan codes.
const fn same(c: u16) -> Key {
    k(c, c, false)
}

